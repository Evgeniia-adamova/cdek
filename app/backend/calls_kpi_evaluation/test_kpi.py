def test_kpi_analyzer():
    """Тестирует KPI анализатор на примерах"""
    
    print("\n" + "="*80)
    print("ТЕСТ KPI АНАЛИЗАТОРА")
    print("="*80)
    
    # Тест 1: Хороший звонок
    print("\n" + "─"*80)
    print("ТЕСТ 1: Анализ хорошего звонка")
    print("─"*80)
    
    results_good = analyze_call(GOOD_CALL_EXAMPLE)
    
    print(f"\n✓ Анализ завершен")
    print(f"  Оценка: {results_good['overall_score']}/{results_good['max_possible_score']}")
    print(f"  Процент: {results_good['score_percentage']}%")
    print(f"  Статус: {results_good['overall_status']} {results_good['rating']}")
    
    print(f"\n  По категориям:")
    for category, data in results_good['categories'].items():
        print(f"    {category}: {data['total_score']}/{data['max_score']} ({data['percentage']}%)")
    
    # Тест 2: Плохой звонок
    print("\n" + "─"*80)
    print("ТЕСТ 2: Анализ плохого звонка")
    print("─"*80)
    
    results_bad = analyze_call(BAD_CALL_EXAMPLE)
    
    print(f"\n✓ Анализ завершен")
    print(f"  Оценка: {results_bad['overall_score']}/{results_bad['max_possible_score']}")
    print(f"  Процент: {results_bad['score_percentage']}%")
    print(f"  Статус: {results_bad['overall_status']} {results_bad['rating']}")
    
    print(f"\n  По категориям:")
    for category, data in results_bad['categories'].items():
        print(f"    {category}: {data['total_score']}/{data['max_score']} ({data['percentage']}%)")
    
    # Сохраняем результаты
    print("\n" + "─"*80)
    print("Сохранение результатов тестирования...")
    print("─"*80)
    
    test_results = {
        'timestamp': __import__('datetime').datetime.now().isoformat(),
        'test_cases': [
            {
                'name': 'Хороший звонок',
                'score': results_good['overall_score'],
                'percentage': results_good['score_percentage'],
                'status': results_good['overall_status'],
                'details': results_good
            },
            {
                'name': 'Плохой звонок',
                'score': results_bad['overall_score'],
                'percentage': results_bad['score_percentage'],
                'status': results_bad['overall_status'],
                'details': results_bad
            }
        ]
    }
    
    # Сохраняем в файл
    output_file = Path(__file__).parent / "test_results.json"
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(test_results, f, ensure_ascii=False, indent=2)
    
    print(f"✓ Результаты тестирования сохранены в {output_file}")
    
    print("\n" + "="*80)
    print("ТЕСТИРОВАНИЕ ЗАВЕРШЕНО")
    print("="*80 + "\n")
    
    return test_results


if __name__ == "__main__":
    test_kpi_analyzer()
